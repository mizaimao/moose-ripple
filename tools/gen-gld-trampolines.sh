#!/bin/sh
# Generate x86_64 trampolines for the gld* entry points: each exported gldX jumps through
# slot i of real_gld[] with all registers and stack untouched, so argument types don't matter.
#   gen-gld-trampolines.sh LIST OUT.s OUT-names.h
set -eu
list=$1 asm=$2 hdr=$3
names=$(grep -v '^#' "$list" | grep -v '^$')
{
    echo "/* Generated by tools/gen-gld-trampolines.sh from $(basename "$list"). */"
    echo "	.text"
    i=0
    for n in $names; do
        echo "	.globl _$n"
        echo "	.p2align 4"
        echo "_$n:"
        echo "	jmpq	*_real_gld+$((i * 8))(%rip)"
        i=$((i + 1))
    done
} > "$asm"
{
    echo "/* Generated by tools/gen-gld-trampolines.sh from $(basename "$list"). */"
    echo "#define GLD_COUNT $(echo "$names" | wc -l | tr -d ' ')"
    echo "static const char *const gld_names[GLD_COUNT] = {"
    for n in $names; do echo "    \"$n\","; done
    echo "};"
} > "$hdr"
