#define TSS_DTOR_SLOTS 64

/* ---- Helpers -------------------------------------------------------------------------------- */
static DWORD
ms_until(const struct timespec *abs_time)
{
    struct timespec now;
    long long ms;

    timespec_get(&now, TIME_UTC);
    ms = ((long long)abs_time->tv_sec - now.tv_sec) * 1000 +
         (abs_time->tv_nsec - now.tv_nsec) / 1000000;
    if (ms <= 0)
        return 0;
    return ms > 0x7FFFFFFF ? 0x7FFFFFFF : (DWORD)ms;
}

/* The semaphore behind *slot, created when first needed. */
static HANDLE
lazy_semaphore(void *volatile *slot)
{
    HANDLE h = (HANDLE)*slot;
    if (!h) {
        h = CreateSemaphoreA(NULL, 0, 0x7FFFFFFF, NULL);
        if (!h)
            abort();
        if (InterlockedCompareExchangePointer(slot, h, NULL) != NULL) {
            CloseHandle(h);
            h = (HANDLE)*slot;
        }
    }
    return h;
}

/* ---- 7.25.2 Initialization functions -------------------------------------------------------- */
void
call_once(once_flag *flag, void (*func)(void))
{
    LONG volatile *status = (LONG volatile *)&flag->status;
    unsigned tries = 0;

    for (;;) {
        LONG s = *status;
        if (s == 2)
            return;
        if (s == 0 && InterlockedCompareExchange(status, 1, 0) == 0) {
            func();
            InterlockedExchange(status, 2);
            return;
        }
        Sleep(++tries < 16 ? 0 : 1);      /* another thread is in func */
    }
}

/* ---- 7.25.4 Mutex functions ------------------------------------------------------------------ */
void
mtx_destroy(mtx_t *mtx)
{
    assert(mtx);
    if (mtx->LockSemaphore) {
        CloseHandle((HANDLE)mtx->LockSemaphore);
        mtx->LockSemaphore = NULL;
    }
}

int
mtx_init(mtx_t *mtx, int type)
{
    assert(mtx != NULL);
    if (type != mtx_plain && type != mtx_timed
      && type != (mtx_plain|mtx_recursive)
      && type != (mtx_timed|mtx_recursive))
        return thrd_error;
    memset(mtx, 0, sizeof *mtx);
    return thrd_success;
}

static int
mtx_lock_ms(mtx_t *mtx, DWORD ms)
{
    void *self = (void *)(uintptr_t)GetCurrentThreadId();

    if (mtx->OwningThread == self) {
        mtx->RecursionCount++;
        return thrd_success;
    }
    if (InterlockedIncrement(&mtx->LockCount) > 1) {
        HANDLE sem = lazy_semaphore((void *volatile *)&mtx->LockSemaphore);
        if (WaitForSingleObject(sem, ms) != WAIT_OBJECT_0) {
            /* Timed out. Step back out of the line, unless the holder has just handed the
               mutex over (the count no longer includes it): then the token is ours. */
            for (;;) {
                LONG n = mtx->LockCount;
                if (WaitForSingleObject(sem, 0) == WAIT_OBJECT_0)
                    break;
                if (n > 1 && InterlockedCompareExchange(&mtx->LockCount, n - 1, n) == n)
                    return thrd_timedout;
                Sleep(0);
            }
        }
    }
    mtx->OwningThread = self;
    mtx->RecursionCount = 1;
    return thrd_success;
}

int
mtx_lock(mtx_t *mtx)
{
    assert(mtx != NULL);
    return mtx_lock_ms(mtx, INFINITE);
}

int
mtx_timedlock(mtx_t *mtx, const struct timespec *ts)
{
    assert(mtx != NULL);
    assert(ts != NULL);
    return mtx_lock_ms(mtx, ms_until(ts));
}

int
mtx_trylock(mtx_t *mtx)
{
    void *self = (void *)(uintptr_t)GetCurrentThreadId();

    assert(mtx != NULL);
    if (mtx->OwningThread == self) {
        mtx->RecursionCount++;
        return thrd_success;
    }
    if (InterlockedCompareExchange(&mtx->LockCount, 1, 0) != 0)
        return thrd_busy;
    mtx->OwningThread = self;
    mtx->RecursionCount = 1;
    return thrd_success;
}

int
mtx_unlock(mtx_t *mtx)
{
    assert(mtx != NULL);
    if (--mtx->RecursionCount > 0)
        return thrd_success;
    mtx->OwningThread = NULL;
    if (InterlockedDecrement(&mtx->LockCount) > 0)
        ReleaseSemaphore(lazy_semaphore((void *volatile *)&mtx->LockSemaphore), 1, NULL);
    return thrd_success;
}

/* ---- 7.25.3 Condition variable functions ----------------------------------------------------- */
/* A semaphore, and the number of waiters nobody has woken yet. A waker takes one (or all) of
   that count and releases as many semaphore tokens; a waiter that times out takes its own
   count back, or, when a waker was faster, the token meant for it. */
struct cond {
    HANDLE sem;
    LONG volatile waiters;
};

static struct cond *
cond_get(cnd_t *cond)
{
    struct cond *c = (struct cond *)cond->Ptr;
    if (!c) {
        c = (struct cond *)calloc(1, sizeof *c);
        if (!c)
            abort();
        c->sem = CreateSemaphoreA(NULL, 0, 0x7FFFFFFF, NULL);
        if (InterlockedCompareExchangePointer((void *volatile *)&cond->Ptr, c, NULL) != NULL) {
            CloseHandle(c->sem);
            free(c);
            c = (struct cond *)cond->Ptr;
        }
    }
    return c;
}

int
cnd_init(cnd_t *cond)
{
    assert(cond != NULL);
    cond->Ptr = NULL;
    return cond_get(cond) ? thrd_success : thrd_nomem;
}

void
cnd_destroy(cnd_t *cond)
{
    struct cond *c;

    assert(cond != NULL);
    c = (struct cond *)cond->Ptr;
    if (c) {
        cond->Ptr = NULL;
        CloseHandle(c->sem);
        free(c);
    }
}

int
cnd_signal(cnd_t *cond)
{
    struct cond *c;

    assert(cond != NULL);
    c = (struct cond *)cond->Ptr;
    while (c) {
        LONG n = c->waiters;
        if (n <= 0)
            break;
        if (InterlockedCompareExchange(&c->waiters, n - 1, n) == n) {
            ReleaseSemaphore(c->sem, 1, NULL);
            break;
        }
    }
    return thrd_success;
}

int
cnd_broadcast(cnd_t *cond)
{
    struct cond *c;

    assert(cond != NULL);
    c = (struct cond *)cond->Ptr;
    if (c) {
        LONG n = InterlockedExchange(&c->waiters, 0);
        if (n > 0)
            ReleaseSemaphore(c->sem, n, NULL);
    }
    return thrd_success;
}

static int
cond_wait_ms(cnd_t *cond, mtx_t *mtx, DWORD ms)
{
    struct cond *c = cond_get(cond);
    long depth = mtx->RecursionCount;
    bool woken;

    InterlockedIncrement(&c->waiters);
    mtx->RecursionCount = 1;
    mtx_unlock(mtx);
    woken = WaitForSingleObject(c->sem, ms) == WAIT_OBJECT_0;
    while (!woken) {
        LONG n = c->waiters;
        if (n <= 0) {
            WaitForSingleObject(c->sem, INFINITE);
            woken = true;
        } else if (InterlockedCompareExchange(&c->waiters, n - 1, n) == n)
            break;
    }
    mtx_lock(mtx);
    mtx->RecursionCount = depth;
    return woken ? thrd_success : thrd_timedout;
}

int
cnd_timedwait(cnd_t *cond, mtx_t *mtx, const struct timespec *abs_time)
{
    assert(cond != NULL);
    assert(mtx != NULL);
    assert(abs_time != NULL);
    return cond_wait_ms(cond, mtx, ms_until(abs_time));
}

int
cnd_wait(cnd_t *cond, mtx_t *mtx)
{
    assert(cond != NULL);
    assert(mtx != NULL);
    return cond_wait_ms(cond, mtx, INFINITE);
}

/* ---- 7.25.6 Thread-specific storage ---------------------------------------------------------- */
static struct {
    tss_t key;
    tss_dtor_t dtor;
} tss_dtors[TSS_DTOR_SLOTS];
static LONG volatile tss_dtors_lock;

static void
tss_dtors_enter(void)
{
    while (InterlockedCompareExchange(&tss_dtors_lock, 1, 0) != 0)
        Sleep(0);
}

int
tss_create(tss_t *key, tss_dtor_t dtor)
{
    int i;

    assert(key != NULL);
    *key = TlsAlloc();
    if (*key == TLS_OUT_OF_INDEXES)
        return thrd_error;
    if (dtor) {
        tss_dtors_enter();
        for (i = 0; i < TSS_DTOR_SLOTS; i++) {
            if (!tss_dtors[i].dtor) {
                tss_dtors[i].key = *key;
                tss_dtors[i].dtor = dtor;
                break;
            }
        }
        InterlockedExchange(&tss_dtors_lock, 0);
        if (i == TSS_DTOR_SLOTS) {
            TlsFree(*key);
            return thrd_error;
        }
    }
    return thrd_success;
}

void
tss_delete(tss_t key)
{
    int i;

    tss_dtors_enter();
    for (i = 0; i < TSS_DTOR_SLOTS; i++) {
        if (tss_dtors[i].dtor && tss_dtors[i].key == key)
            tss_dtors[i].dtor = NULL;
    }
    InterlockedExchange(&tss_dtors_lock, 0);
    TlsFree(key);
}

void *
tss_get(tss_t key)
{
    return TlsGetValue(key);
}

int
tss_set(tss_t key, void *val)
{
    return TlsSetValue(key, val) ? thrd_success : thrd_error;
}

/* ---- 7.25.5 Thread functions ----------------------------------------------------------------- */
struct thread_state {
    thrd_t thrd;
    bool close_handle;          /* the handle was made by thrd_current: ours to close */
};

static thread_local struct thread_state current_thread = { { NULL }, false };

struct thread_start {
    thrd_start_t func;
    void *arg;
    thrd_t thrd;
};

/* Called when a thread ends. Mesa calls it from a C++ thread_local destructor
   (threads_win32_tls_callback.cpp), which in this build never runs: the object is never used,
   so no destructor is registered. The driver's entry point calls it there instead
   (DLL_THREAD_DETACH, patch 0009). */
void
__threads_win32_tls_callback(void)
{
    struct thread_state *state = &current_thread;
    int i;

    for (i = 0; i < TSS_DTOR_SLOTS; i++) {
        tss_dtor_t dtor = tss_dtors[i].dtor;
        if (dtor) {
            void *val = TlsGetValue(tss_dtors[i].key);
            if (val) {
                TlsSetValue(tss_dtors[i].key, NULL);
                dtor(val);
            }
        }
    }
    if (state->close_handle) {
        state->close_handle = false;
        CloseHandle((HANDLE)state->thrd.handle);
    }
}

static unsigned __stdcall
thread_routine(void *p)
{
    struct thread_start start = *(struct thread_start *)p;

    free(p);
    current_thread.thrd = start.thrd;
    current_thread.close_handle = false;
    return (unsigned)start.func(start.arg);
}

int
thrd_create(thrd_t *thr, thrd_start_t func, void *arg)
{
    struct thread_start *start;
    uintptr_t handle;
    unsigned id;

    assert(thr != NULL);
    start = (struct thread_start *)malloc(sizeof *start);
    if (!start)
        return thrd_nomem;
    start->func = func;
    start->arg = arg;
    /* Windows 98 wants the thread ID pointer: NULL there makes thread creation fail. */
    handle = _beginthreadex(NULL, 0, thread_routine, start, CREATE_SUSPENDED, &id);
    if (handle == 0) {
        free(start);
        return (errno == EAGAIN || errno == EACCES) ? thrd_nomem : thrd_error;
    }
    thr->handle = (void *)handle;
    start->thrd = *thr;
    ResumeThread((HANDLE)handle);
    return thrd_success;
}

thrd_t
thrd_current(void)
{
    struct thread_state *state = &current_thread;

    if (state->thrd.handle == NULL) {
        /* A thread Mesa didn't start: a real handle from the pseudo-handle. */
        HANDLE h;
        if (!DuplicateHandle(GetCurrentProcess(), GetCurrentThread(), GetCurrentProcess(),
                             &h, 0, FALSE, DUPLICATE_SAME_ACCESS))
            abort();
        state->thrd.handle = (void *)h;
        state->close_handle = true;
    }
    return state->thrd;
}

int
thrd_detach(thrd_t thr)
{
    CloseHandle((HANDLE)thr.handle);
    return thrd_success;
}

int
thrd_equal(thrd_t thr0, thrd_t thr1)
{
    return thr0.handle == thr1.handle;
}

_Noreturn void
thrd_exit(int res)
{
    _endthreadex((unsigned)res);
    abort();
}

int
thrd_join(thrd_t thr, int *res)
{
    DWORD code;

    if (WaitForSingleObject((HANDLE)thr.handle, INFINITE) != WAIT_OBJECT_0)
        return thrd_error;
    if (res) {
        if (!GetExitCodeThread((HANDLE)thr.handle, &code)) {
            CloseHandle((HANDLE)thr.handle);
            return thrd_error;
        }
        *res = (int)code;
    }
    CloseHandle((HANDLE)thr.handle);
    return thrd_success;
}

int
thrd_sleep(const struct timespec *time_point, struct timespec *remaining)
{
    (void)remaining;
    assert(time_point);
    Sleep((DWORD)(time_point->tv_sec * 1000 + time_point->tv_nsec / 1000000));
    return 0;
}

void
thrd_yield(void)
{
    Sleep(0);
}
