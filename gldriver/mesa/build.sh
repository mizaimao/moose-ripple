#!/bin/sh
# Cross-build Mesa for Mac OS X 10.6 on dev.lan: GL, the virgl Gallium driver, our winsys
# (overlay/src/gallium/winsys/virgl/ripple) and CGL frontend. One architecture per run:
#   gldriver/mesa/build.sh x86_64|i386 [--clean] [NINJA-TARGETS]
# Pinned Mesa source (decision 0009), unpacked into .tools/mesa/src-VERSION, patched with
# patches/*.patch and overlaid with overlay/; build directory .tools/mesa/build-ARCH.
# The source tree is unpacked again when the patches change (or with --clean); overlay
# files are synced by content, so editing them rebuilds only what depends on them.
set -eu

ARCH=${1:?usage: build.sh x86_64|i386 [--clean] [targets]}
shift
CLEAN=0
[ "${1:-}" = --clean ] && { CLEAN=1; shift; }
case $ARCH in
    x86_64) CPU_FAMILY=x86_64; CPU=x86_64 ;;
    i386)   CPU_FAMILY=x86;    CPU=i686 ;;
    *) echo "unknown architecture $ARCH" >&2; exit 1 ;;
esac

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
HERE=$ROOT/gldriver/mesa
T=$ROOT/.tools
MESA_VERSION=24.3.4
MESA_SHA256=e641ae27191d387599219694560d221b7feaa91c900bcec46bf444218ed66025
TARBALL=$T/src/mesa-dl/mesa-$MESA_VERSION.tar.xz
SRC=$T/mesa/src-$MESA_VERSION
BUILD=$T/mesa/build-$ARCH
SDK=$T/sdk/MacOSX10.6.sdk
CCT=$T/cctools/bin/x86_64-apple-darwin10-
export PATH="$ROOT/.venv/bin:$T/gnu/bin:$PATH"     # meson + mako; flex/bison if in .tools

# ---- Source tree -------------------------------------------------------------------------
if [ ! -f "$TARBALL" ]; then
    mkdir -p "$(dirname "$TARBALL")"
    curl -sfLo "$TARBALL" "https://archive.mesa3d.org/mesa-$MESA_VERSION.tar.xz"
fi
echo "$MESA_SHA256  $TARBALL" | sha256sum -c --quiet

stamp=$( (echo "$MESA_SHA256"; cat "$HERE"/patches/*.patch) | sha256sum | cut -c1-16)
if [ "$CLEAN" = 1 ] || [ "$(cat "$SRC/.ripple-stamp" 2>/dev/null)" != "$stamp" ]; then
    echo "unpacking Mesa $MESA_VERSION and applying $(ls "$HERE"/patches/*.patch | wc -l) patches"
    rm -rf "$SRC" "$T"/mesa/build-*
    mkdir -p "$T/mesa"
    tar -C "$T/mesa" -xf "$TARBALL"
    mv "$T/mesa/mesa-$MESA_VERSION" "$SRC"
    for p in "$HERE"/patches/*.patch; do
        patch -s -d "$SRC" -p1 < "$p"
    done
    echo "$stamp" > "$SRC/.ripple-stamp"
fi
rsync -rc "$HERE/overlay/" "$SRC/"
cmp -s "$ROOT/include/ripple_gpu_uapi.h" "$SRC/src/gallium/winsys/virgl/ripple/ripple_gpu_uapi.h" ||
    cp "$ROOT/include/ripple_gpu_uapi.h" "$SRC/src/gallium/winsys/virgl/ripple/"

# ---- Configure ---------------------------------------------------------------------------
if [ ! -f "$BUILD/build.ninja" ]; then
    mkdir -p "$BUILD"
    cat > "$BUILD.cross.ini" <<EOF
# Generated by gldriver/mesa/build.sh: Mac OS X 10.6 ($ARCH) with clang, the 10.6 SDK and
# cctools-port ld64 (docs/decisions/0001-toolchain.md).
[constants]
target = ['-target', '$ARCH-apple-macosx10.6', '-isysroot', '$SDK', '--ld-path=${CCT}ld', '-mlinker-version=609']

[binaries]
c = ['clang'] + target
cpp = ['clang++'] + target + ['-stdlib=libstdc++']
objc = ['clang'] + target
ar = '${CCT}ar'
ranlib = '${CCT}ranlib'
strip = '${CCT}strip'
pkg-config = 'false'

[built-in options]
# RIPPLE_NO_TLS: no thread-local variables before 10.7 (patches 0001, 0002).
c_args = ['-DRIPPLE_NO_TLS', '-include', '$HERE/compat/ripple_compat.h']
cpp_args = ['-DRIPPLE_NO_TLS', '-include', '$HERE/compat/ripple_compat.h']
objc_args = ['-DRIPPLE_NO_TLS']
c_link_args = ['-Wl,-no_function_starts', '-Wl,-no_data_in_code_info']
cpp_link_args = ['-Wl,-no_function_starts', '-Wl,-no_data_in_code_info']

[properties]
needs_exe_wrapper = true
# The 10.6 SDK, for Apple's gliDispatch.h (frontends/cgl/gen_dispatch.py).
ripple_sdk = '$SDK'

[host_machine]
system = 'darwin'
cpu_family = '$CPU_FAMILY'
cpu = '$CPU'
endian = 'little'
EOF
    meson setup "$BUILD" "$SRC" --cross-file "$BUILD.cross.ini" --wrap-mode=nodownload \
        --buildtype=release -Db_ndebug=true \
        -Dplatforms= -Dglx=disabled -Degl=disabled -Dgbm=disabled -Dglvnd=disabled \
        -Dopengl=true -Dgles1=disabled -Dgles2=disabled -Dshared-glapi=disabled \
        -Dgallium-drivers=virgl -Dvulkan-drivers= -Dllvm=disabled -Dosmesa=false \
        -Dgallium-vdpau=disabled -Dgallium-va=disabled -Dgallium-xa=disabled \
        -Dgallium-nine=false -Dgallium-opencl=disabled -Dgallium-rusticl=false \
        -Dvideo-codecs= -Dtools= -Dbuild-tests=false -Dhtml-docs=disabled \
        -Dshader-cache=disabled -Dexpat=disabled -Dxmlconfig=disabled -Dzstd=disabled \
        -Dvalgrind=disabled -Dlibunwind=disabled -Dlmsensors=disabled -Dperfetto=false \
        -Dmicrosoft-clc=disabled -Dintel-clc=disabled > "$BUILD.configure.log" 2>&1 ||
        { tail -30 "$BUILD.configure.log" >&2; exit 1; }
fi

# ---- Build -------------------------------------------------------------------------------
ninja -C "$BUILD" "$@"
